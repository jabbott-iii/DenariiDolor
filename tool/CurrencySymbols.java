import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Comparator;
import java.util.Currency;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.SortedMap;
import java.util.TreeMap;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Writes lib/l10n/currency_symbols.dart: the symbol that each locale of the app's seven languages writes for every currency
 * with two decimals, such as `US$` for US dollars in British English. `package:intl` has one symbol per currency for every
 * language, so the app takes these from the Unicode CLDR data that the JDK carries (ADR-0016).
 *
 * <p>Run it from the repository root with Java 25, which carries CLDR 47, then format the output, as CI does:
 *
 * <pre>
 *     java tool/CurrencySymbols.java &gt; lib/l10n/currency_symbols.dart
 *     dart format lib/l10n/currency_symbols.dart
 * </pre>
 *
 * <p>Another Java release would write other symbols, so the tool refuses one.
 */
public final class CurrencySymbols {
    private static final int JAVA_RELEASE = 25;

    /** The languages of the app's packs (`lib/l10n/app_*.arb`). */
    private static final List<String> LANGUAGES = List.of("ar", "en", "es", "fr", "hi", "pt", "zh");

    private static final String HEADER = """
        /*
         * Copyright (c) 2026 Joseph Anthony Abbott III. All rights reserved.
         * Proprietary and confidential. Use is governed by the LICENSE file; copying, modifying or distributing this file without
         * written permission is prohibited.
         */

        // Generated by tool/CurrencySymbols.java from the locale data of Java %d (Unicode CLDR %s). Don't edit by hand; rerun
        // the tool (ADR-0016).

        /// The symbol each locale writes for a currency with two decimals, keyed by the locale's BCP 47 tag and then by the
        /// currency's ISO 4217 code.
        ///
        /// A language's own entry, such as `'en'`, lists the symbols that differ from the code. Every other locale lists only
        /// the symbols that differ from its language's, even where that symbol is the code itself (`'en-AU'` writes US dollars
        /// as `USD`). A currency that neither lists is written as its code.
        const Map<String, Map<String, String>> currencySymbols = {
        """;

    private CurrencySymbols() {}

    public static void main(String[] args) throws IOException {
        if (Runtime.version().feature() != JAVA_RELEASE) {
            System.err.printf("Run this with Java %d, not %s: each release carries other CLDR data.%n", JAVA_RELEASE,
                Runtime.version());
            System.exit(1);
        }
        List<Currency> currencies = Currency.getAvailableCurrencies().stream()
            .filter(currency -> currency.getDefaultFractionDigits() == 2)
            .sorted(Comparator.comparing(Currency::getCurrencyCode))
            .toList();

        SortedMap<String, Locale> locales = new TreeMap<>();
        for (Locale locale : Locale.getAvailableLocales()) {
            if (LANGUAGES.contains(locale.getLanguage()) && locale.getVariant().isEmpty() && !locale.hasExtensions()) {
                locales.put(locale.toLanguageTag(), locale);
            }
        }
        for (String language : LANGUAGES) {
            if (!locales.containsKey(language)) {
                throw new IllegalStateException("Java has no locale data for " + language);
            }
        }

        StringBuilder out = new StringBuilder(String.format(HEADER, JAVA_RELEASE, cldrVersion()));
        for (Map.Entry<String, Locale> entry : locales.entrySet()) {
            Locale locale = entry.getValue();
            Locale language = Locale.forLanguageTag(locale.getLanguage());
            boolean isLanguage = locale.equals(language);
            out.append("  ").append(dartString(entry.getKey())).append(": {");
            for (Currency currency : currencies) {
                String code = currency.getCurrencyCode();
                String symbol = currency.getSymbol(locale);
                String inherited = isLanguage ? code : currency.getSymbol(language);
                if (!symbol.equals(inherited)) {
                    out.append(dartString(code)).append(": ").append(dartString(symbol)).append(", ");
                }
            }
            out.append("},\n");
        }
        out.append("};\n");
        System.out.print(out);
    }

    /** The CLDR release that the running JDK's legal notice names, such as `47`. */
    private static String cldrVersion() throws IOException {
        Path notice = Path.of(System.getProperty("java.home"), "legal", "java.base", "cldr.md");
        Matcher match = Pattern.compile("\\(CLDR\\) v(\\d+(?:\\.\\d+)*)").matcher(Files.readString(notice));
        if (!match.find()) {
            throw new IllegalStateException("No CLDR version in " + notice);
        }
        return match.group(1);
    }

    /**
     * [text] as a single-quoted Dart string. Invisible characters, such as the right-to-left mark after an Arabic symbol,
     * are escaped, so a reader can see them.
     */
    private static String dartString(String text) {
        StringBuilder out = new StringBuilder("'");
        text.codePoints().forEach(codePoint -> {
            int type = Character.getType(codePoint);
            if (codePoint == '\\' || codePoint == '\'' || codePoint == '$') {
                out.append('\\').appendCodePoint(codePoint);
            } else if (type == Character.FORMAT || type == Character.CONTROL
                || (type == Character.SPACE_SEPARATOR && codePoint != ' ')) {
                out.append(String.format("\\u{%X}", codePoint));
            } else {
                out.appendCodePoint(codePoint);
            }
        });
        return out.append('\'').toString();
    }
}
