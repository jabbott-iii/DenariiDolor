"""Writes src/text/unicode_tables.rs: the decimal digits and currency signs that money parsing recognizes.

v1's Kotlin code read text one UTF-16 code unit at a time, so it recognized only characters in the Basic Multilingual Plane
(U+0000 to U+FFFF). The tables keep that limit, so the Rust port accepts and rejects the same input.

Run from rust/crates/core, with Python's own Unicode data (the version is written into the file):

    python3 -I tools/unicode_tables.py | rustfmt --edition 2024 > src/text/unicode_tables.rs

CI's `cargo fmt --check` fails if the file isn't formatted, which is why the output goes through rustfmt.
"""

import unicodedata

BMP_END = 0x10000

HEADER = """/*
 * Copyright (c) 2026 Joseph Anthony Abbott III. All rights reserved.
 * Proprietary and confidential. Use is governed by the LICENSE file; copying, modifying or distributing this file without
 * written permission is prohibited.
 */

//! Generated by `tools/unicode_tables.py` from Unicode {version}. Don't edit by hand; rerun the script.
"""


def decimal_zeros() -> list[int]:
    """The first code point of each run of ten decimal digits (category Nd) in the Basic Multilingual Plane."""
    zeros = [c for c in range(BMP_END) if unicodedata.category(chr(c)) == "Nd" and unicodedata.decimal(chr(c)) == 0]
    for zero in zeros:
        for value in range(10):
            char = chr(zero + value)
            assert unicodedata.category(char) == "Nd" and unicodedata.decimal(char) == value, hex(zero)
    digits = sum(1 for c in range(BMP_END) if unicodedata.category(chr(c)) == "Nd")
    assert digits == 10 * len(zeros), "every decimal digit belongs to a run of ten"
    return zeros


def currency_ranges() -> list[tuple[int, int]]:
    """Inclusive ranges of the currency symbols (category Sc) in the Basic Multilingual Plane."""
    ranges: list[tuple[int, int]] = []
    for c in range(BMP_END):
        if unicodedata.category(chr(c)) != "Sc":
            continue
        if ranges and ranges[-1][1] == c - 1:
            ranges[-1] = (ranges[-1][0], c)
        else:
            ranges.append((c, c))
    return ranges


def main() -> None:
    print(HEADER.format(version=unicodedata.unidata_version), end="")
    zeros = decimal_zeros()
    print()
    print("/// The first code point of each run of ten decimal digits (`0` to `9`), in ascending order.")
    print(f"pub(super) const DECIMAL_ZEROS: [u32; {len(zeros)}] = [")
    for zero in zeros:
        print(f"    0x{zero:04X},")
    print("];")
    ranges = currency_ranges()
    print()
    print("/// Inclusive ranges of currency symbols, in ascending order.")
    print(f"pub(super) const CURRENCY_SYMBOLS: [(u32, u32); {len(ranges)}] = [")
    for start, end in ranges:
        print(f"    (0x{start:04X}, 0x{end:04X}),")
    print("];")


main()
